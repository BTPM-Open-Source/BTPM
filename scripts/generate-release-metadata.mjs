#!/usr/bin/env node
/**
 * generate-release-metadata.mjs — Writes src/release/releaseMetadata.generated.ts
 * containing APP_VERSION, BUILD_VERSION, RELEASED_AT_UTC.
 *
 * APP_VERSION   = package.json version (stable across builds within a step)
 * BUILD_VERSION = `${APP_VERSION}+${UTC compact timestamp}` (fresh each build)
 * RELEASED_AT_UTC = ISO-8601 UTC timestamp
 *
 * Failure is fatal — build must not silently produce stale metadata.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgPath = resolve(__dirname, "..", "package.json");
const outDir = resolve(__dirname, "..", "src", "release");
const outFile = resolve(outDir, "releaseMetadata.generated.ts");

try {
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  const appVersion = String(pkg.version || "").trim();
  if (!/^\d+\.\d+\.\d+$/.test(appVersion)) {
    throw new Error(`Invalid package.json version: "${appVersion}"`);
  }
  const now = new Date();
  const releasedAt = now.toISOString();
  // Compact UTC stamp: YYYYMMDDTHHMMSSZ
  const stamp = releasedAt.replace(/[-:]/g, "").replace(/\.\d{3}/, "");
  const buildVersion = `${appVersion}+${stamp}`;

  mkdirSync(outDir, { recursive: true });
  const contents = `// AUTO-GENERATED by scripts/generate-release-metadata.mjs — do not edit by hand.
export const APP_VERSION = ${JSON.stringify(appVersion)};
export const BUILD_VERSION = ${JSON.stringify(buildVersion)};
export const RELEASED_AT_UTC = ${JSON.stringify(releasedAt)};
`;
  writeFileSync(outFile, contents, "utf8");
  console.log(`[release-metadata] APP=${appVersion} BUILD=${buildVersion}`);
} catch (err) {
  console.error("[release-metadata] FAILED:", err?.message || err);
  process.exit(1);
}
